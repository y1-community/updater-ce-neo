"""Diagnostics, persistent logging, and log file export for Updater CE.

Captures, persists, categorizes, and displays diagnostic logs from:
1. Updater CE GUI (application events, downloads, extraction, scatter parsing)
2. SP Flash Tool console mode (stdout, stderr, QT_FLASH_TOOL.log)
3. MTKClient (terminal output, DA communications, USB handshakes)
4. Full unified diagnostic stream
"""

